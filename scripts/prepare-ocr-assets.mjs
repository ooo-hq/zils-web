import {copyFile,mkdir,readdir} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {dirname,join} from 'node:path';
const require=createRequire(import.meta.url);
const target=new URL('../public/_ocr/',import.meta.url);
await mkdir(target,{recursive:true});
const core=dirname(require.resolve('tesseract.js-core/package.json'));
for(const file of await readdir(core)) if (/^tesseract-core.*\.wasm(?:\.js)?$/.test(file)) await copyFile(join(core,file),new URL(file,target));
await copyFile(require.resolve('tesseract.js/dist/worker.min.js'),new URL('worker.min.js',target));
await copyFile(require.resolve('@tesseract.js-data/eng/4.0.0_best_int/eng.traineddata.gz'),new URL('eng.traineddata.gz',target));
await copyFile(require.resolve('tesseract.js/LICENSE.md'),new URL('tesseract-LICENSE.md',target));
await copyFile(require.resolve('tesseract.js/dist/worker.min.js.LICENSE.txt'),new URL('worker.min.js.LICENSE.txt',target));
await copyFile(join(core,'LICENSE'),new URL('tesseract-core-LICENSE',target));
