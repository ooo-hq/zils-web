export type Verdict = 'pass' | 'fail';
export type Example = {
  id: string; title: string; brand: string; tag: string; summary: string;
  analysis: string; brief: string; content: string; productionReasoning: string;
  decisions: { production: Verdict; base: Verdict; zils: Verdict; jev: Verdict };
};
export type Reply = { id: string; content: string; previous: string | null; intent: string; jev: string; expected: string; before: string };
export type Move = { uci: string; label: string; fromSquare: string; toSquare: string; board: string; mate: boolean };
export type Position = { id: string; title: string; side: string; board: string; moves: Move[]; zils: string; jev: string; before: string };

const verdictLabel = (value: Verdict) => value === 'pass' ? 'Approve' : 'Do not approve';

export function PostDemo({ examples }: { examples: Example[] }) {
  const [index, setIndex] = useState(0);
  const e = examples[index];
  const excerpt = e.id === 'T0792' ? e.content.slice(e.content.indexOf('Now that wallet')) : e.content;
  const quote = excerpt.length > 500 ? `${excerpt.slice(0, 480)}…` : excerpt;
  const right = (v: Verdict) => v === e.decisions.production;
  return <>
    <StageHead title="Should this creator post be approved?"><button type="button" className={base.exBtn} onClick={() => setIndex((index + 1) % examples.length)}>Another post →</button></StageHead>
    <div className={s.post}>
      <p className={s.bubble} data-post-quote>“{quote}”<span className={s.src}>Creator post · {e.brand} campaign</span></p>
      <Verdicts rows={{ zils: { answer: verdictLabel(e.decisions.zils), right: right(e.decisions.zils) }, jev: { answer: verdictLabel(e.decisions.jev), right: right(e.decisions.jev) } }} note="Right = matches Bitcast’s label" />
    </div>
    <DetailsRow summary="Behind this decision" key={e.id}>
      <div className={base.exBehind}>
        <p>{e.analysis}</p>
        <p>Before training: <strong>{verdictLabel(e.decisions.base)}</strong>. Zils: <strong>{verdictLabel(e.decisions.zils)}</strong>. Bitcast’s label: <strong>{verdictLabel(e.decisions.production)}</strong>. Supplied JEV: <strong>{verdictLabel(e.decisions.jev)}</strong>.</p>
        <p>Our interpretation of recorded choices. The explanation above is editorial, not generated by the model. Source record: {e.id}.</p>
        {e.productionReasoning && <p>Bitcast’s recorded explanation: {e.productionReasoning}</p>}
        {quote !== e.content && <details><summary>Read the full post</summary><p>{e.content}</p></details>}
      </div>
    </DetailsRow>
  </>;
}

const pieces: Record<string, string> = { K: '♚', Q: '♛', R: '♜', B: '♝', N: '♞', P: '♟', k: '♚', q: '♛', r: '♜', b: '♝', n: '♞', p: '♟' };
const pieceNames: Record<string, string> = { k: 'king', q: 'queen', r: 'rook', b: 'bishop', n: 'knight', p: 'pawn' };

export function ChessDemo({ positions }: { positions: Position[] }) {
  const [index, setIndex] = useState(0);
  const [selected, setSelected] = useState<string | null>(null);
  const position = positions[index];
  const zilsMove = position.moves.find(m => m.uci === position.zils)!;
  const jevMove = position.moves.find(m => m.uci === position.jev)!;
  const move = position.moves.find(m => m.uci === selected);
  const board = move?.board ?? position.board;
  const description = [...board].flatMap((p, i) => p === '.' ? [] : [`${p === p.toUpperCase() ? 'White' : 'Black'} ${pieceNames[p.toLowerCase()]} on ${'abcdefgh'[i % 8]}${8 - Math.floor(i / 8)}`]).join(', ');
  const side = position.side === 'white' ? 'White' : 'Black';
  return <>
    <StageHead title={`${side} to move. Which check is mate?`}>
      {positions.length > 1 && <button type="button" className={base.exBtn} onClick={() => { setIndex((index + 1) % positions.length); setSelected(null); }}>Another position →</button>}
    </StageHead>
    <div className={s.chess}>
      <div className={s.board} role="img" aria-label={`Chessboard. ${description}`} data-board>
        {[...board].map((p, i) => {
          const sq = `${'abcdefgh'[i % 8]}${8 - Math.floor(i / 8)}`;
          const light = (Math.floor(i / 8) + i % 8) % 2 === 0;
          return <div key={sq} data-sq={light ? 'l' : 'd'} className={`${s.sqr} ${light ? s.l : s.d} ${move && (sq === move.fromSquare || sq === move.toSquare) ? s.hl : ''}`}>
            {p !== '.' && <span className={p === p.toUpperCase() ? s.w : s.b} aria-hidden="true">{pieces[p]}</span>}
          </div>;
        })}
      </div>
      <div>
        <div className={s.choices}>
          {([['zils', zilsMove], ['jev', jevMove]] as const).map(([model, m]) => <button key={model} type="button" data-choice={model} aria-pressed={selected === m.uci} className={s.choice} onClick={() => setSelected(m.uci)}>
            <span><span className={s.mv}>{m.label}</span><span className={s.by}><Who model={model} /></span></span>
            {selected === m.uci && <span className={`${s.out} ${base.exTag} ${m.mate ? base.exGood : base.exBad}`}>{m.mate ? 'Checkmate' : 'Check, not mate'}</span>}
          </button>)}
        </div>
        <p className={s.hint}>Tap a move to play it.</p>
      </div>
    </div>
    <DetailsRow summary="Behind this move"><div className={base.exBehind}>
      <p>These are three selected examples from the 111 positions in the October 7 chess study where Zils found checkmate and JEV did not. The board replays recorded legal moves; it does not run a live chess model.</p>
      <p>Zils was choosing among supplied checking moves, not playing a full game. A deterministic chess engine solves all positions in this test. Results below include all 512 positions, including Zils’s mistakes.</p>
      <p><a href="/model/chess-study">Read the full chess study</a></p>
    </div></DetailsRow>
  </>;
}

const lane: Record<string, string> = {
  meeting_acceptance: 'var(--zs-lane-billing)', wrong_person: 'var(--zs-lane-spam)', negative: 'var(--zs-lane-spam)',
  not_now: 'var(--zs-lane-account)', pricing_question: 'var(--zs-lane-tech)', referral: 'var(--zs-lane-sales)', opt_out: 'var(--zs-lane-review)',
};

export function InboxDemo({ replies }: { replies: Reply[] }) {
  const [shown, setShown] = useState(0);
  useEffect(() => {
    if (shown === 0 || shown >= replies.length) return;
    const t = setTimeout(() => setShown(shown + 1), 350);
    return () => clearTimeout(t);
  }, [shown, replies.length]);
  const sort = () => setShown(matchMedia('(prefers-reduced-motion: reduce)').matches ? replies.length : 1);
  return <>
    <StageHead title="What does each reply want?"><button type="button" className={`${base.exBtn} ${base.exBtnP}`} onClick={sort}>Sort with Zils</button></StageHead>
    <div className={s.inbox}>
      {replies.map((r, i) => <div key={r.id} className={s.reply}>
        <span className={s.txt}>{r.content}</span>
        <span className={s.intent} data-intent data-shown={i < shown ? '' : undefined} style={{ '--c': lane[r.intent] } as React.CSSProperties}>{r.intent.replace(/_/g, ' ')}</span>
      </div>)}
    </div>
    <DetailsRow summary="Behind these replies"><div className={base.exBehind}>
      <p>These are five selected synthetic examples from the 100-reply Leadpoet test. The intent labels are actual recorded Zils choices.</p>
      <p>The full test includes seven mistakes; all seven had high confidence. One pricing reply containing a misleading instruction was incorrectly marked as an opt-out. These selected examples do not measure production reliability.</p>
    </div></DetailsRow>
  </>;
}
